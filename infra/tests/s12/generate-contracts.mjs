import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { build } from 'esbuild';

const root = process.cwd();
const require = createRequire(path.join(root, '.data/s12-codegen/package.json'));
const Ajv = require('ajv/dist/2020').default;
const standalone = require('ajv/dist/standalone').default;
const addFormats = require('ajv-formats');
const { compile } = require('json-schema-to-typescript');
const raw = await readFile('packages/contracts/contracts.schema.json', 'utf8');
const schema = JSON.parse(raw);
const hash = createHash('sha256').update(raw).digest('hex');
const output = 'apps/commerce/src/plugins/operations/generated';
await mkdir(output, { recursive: true });
async function emit(filename, content) {
  if (process.argv.includes('--check')) {
    if ((await readFile(filename, 'utf8')) !== content) throw new Error(`Generated file differs: ${filename}`);
  } else await writeFile(filename, content);
}
const ajv = new Ajv({
  strict: false,
  allErrors: true,
  code: { source: true, lines: true, esm: true },
  validateFormats: true,
});
addFormats(ajv, { mode: 'full' });
ajv.addSchema(schema, 'contracts');
const names = Object.keys(schema.$defs);
const validators = Object.fromEntries(names.map((name) => [name, `contracts#/$defs/${name}`]));
const source = standalone(ajv, validators);
const bundled = await build({
  stdin: { contents: source, resolveDir: path.join(root, '.data/s12-codegen') },
  bundle: true,
  write: false,
  platform: 'node',
  format: 'esm',
  target: 'es2022',
});
await emit(
  `${output}/validators.ts`,
  `// @ts-nocheck\n// Generated by infra/tests/s12/generate-contracts.mjs. Schema sha256:${hash}\n${bundled.outputFiles[0].text}`,
);
// Conditional invariants stay in the runtime validator. The generated TS shape
// uses the declared properties; the generator otherwise emits unknown indexers.
const structural = JSON.parse(JSON.stringify(schema.$defs, (key, value) => (key === 'allOf' ? undefined : value)));
const typeSchema = {
  type: 'object',
  additionalProperties: false,
  $defs: structural,
  properties: Object.fromEntries(names.map((name) => [name, { $ref: `#/$defs/${name}` }])),
};
await emit(
  `${output}/contracts.ts`,
  await compile(typeSchema, 'Contracts', {
    bannerComment: `/* Generated from packages/contracts/contracts.schema.json; sha256:${hash}. Do not edit. */`,
    unreachableDefinitions: true,
  }),
);
await emit(`${output}/schema-hash.ts`, `// Generated from the common schema.\nexport const schemaHash = '${hash}';\n`);
const licenses = await Promise.all(
  ['ajv', 'ajv-formats'].map(
    async (name) =>
      `${name}\n\n${await readFile(path.join(root, '.data/s12-codegen/node_modules', name, 'LICENSE'), 'utf8')}`,
  ),
);
await emit(`${output}/LICENSES.txt`, licenses.join('\n\n'));
console.log(`Generated ${names.length} validators and contract types from ${hash}.`);
